from __future__ import annotations

import csv
import html
import io
from typing import Any

from config import APP_NAME, APP_VERSION
from modules.header_analysis import analyze_headers
from modules.risk_scoring import assess_risk
from modules.url_analysis import analyze_urls


def build_analysis(record: dict[str, Any]) -> dict[str, Any]:
    parsed = record["parsed"]
    header_findings = analyze_headers(parsed["headers"], parsed["authentication_results"])
    urls = analyze_urls(parsed["body_text"], parsed["body_html"], parsed["links"])
    risk = assess_risk(header_findings, urls, parsed["attachments"], parsed["authentication_results"])
    return {"headers": parsed["headers"], "raw_headers": parsed["raw_headers"], "routing": parsed["received"], "urls": urls, "attachments": parsed["attachments"], "header_findings": header_findings, "risk": risk}


def _e(value: object) -> str:
    return html.escape(str(value), quote=True)


def generate_html_report(record: dict[str, Any], analysis: dict[str, Any]) -> str:
    fields = "".join(f"<tr><th>{_e(key)}</th><td>{_e(value)}</td></tr>" for key, value in analysis["headers"].items())
    urls = "".join(f"<tr><td>{_e(item.get('url'))}</td><td>{_e('; '.join(item.get('reasons', [])) or 'No heuristic flags')}</td></tr>" for item in analysis["urls"])
    attachments = "".join(f"<tr><td>{_e(item.get('filename'))}</td><td>{_e(item.get('mime_type'))}</td><td>{_e(item.get('size'))}</td><td>{_e(item.get('sha256'))}</td></tr>" for item in analysis["attachments"])
    findings = "".join(f"<li><strong>{_e(item['rule'])}</strong> ({_e(item['points'])} points): {_e(item['evidence'])}<br>{_e(item['reason'])}<br>Next: {_e(item['action'])}</li>" for item in analysis["risk"]["findings"])
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Forensic report — {_e(record['filename'])}</title>
<style>body{{font:16px system-ui,sans-serif;max-width:1000px;margin:2rem auto;padding:0 1rem;color:#182230}}table{{border-collapse:collapse;width:100%;margin:1rem 0}}td,th{{border:1px solid #ccd3dc;padding:.55rem;text-align:left;overflow-wrap:anywhere}}th{{background:#edf2f7}}.warning{{background:#fff4d6;padding:1rem;border-left:4px solid #d18c00}}</style></head><body>
<h1>{_e(APP_NAME)} — Forensic Investigation Report</h1><p><b>Investigation ID:</b> {_e(record['investigation_id'])}<br>
<b>Evidence ID:</b> {_e(record['id'])}<br><b>Imported (UTC):</b> {_e(record['imported_at'])}<br>
<b>Original filename:</b> {_e(record['filename'])}<br><b>SHA-256:</b> {_e(record['sha256'])}</p>
<h2>Extracted headers</h2><table>{fields}</table><h3>Raw header excerpt</h3><pre>{_e(analysis['raw_headers'])}</pre>
<h2>Routing analysis</h2><p>Received headers are shown in original order. Chronological reconstruction generally requires reversing that order; this is not sender attribution.</p><ol>{''.join(f'<li>{_e(item)}</li>' for item in analysis['routing'])}</ol>
<h2>URL findings</h2><table><tr><th>URL</th><th>Heuristic indicators</th></tr>{urls}</table>
<h2>Attachment inventory</h2><table><tr><th>Filename</th><th>MIME</th><th>Size</th><th>SHA-256</th></tr>{attachments}</table>
<h2>Risk assessment: {_e(analysis['risk']['score'])}/100 — {_e(analysis['risk']['label'])}</h2><p>Illustrative heuristic triage aid, not a probability or verdict.</p><ul>{findings}</ul>
<p class="warning">Automated parsing and heuristics can produce false positives and false negatives. This report does not establish sender identity, attribution, malware status, or whether metadata is truthful. Hashes establish content integrity only relative to a known reference. SQLite audit controls are not tamper-proof or court-certified evidence preservation.</p>
<footer>Generated by {_e(APP_NAME)} v{_e(APP_VERSION)}.</footer></body></html>"""


def generate_findings_csv(record: dict[str, Any], analysis: dict[str, Any]) -> str:
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=["investigation_id", "evidence_id", "filename", "sha256", "risk_score", "rule", "evidence", "reason", "points", "action"])
    writer.writeheader()
    findings = analysis["risk"]["findings"] or [{"rule": "No scored indicators", "evidence": "", "reason": "", "points": 0, "action": "Continue manual review."}]
    for finding in findings:
        writer.writerow({"investigation_id": record["investigation_id"], "evidence_id": record["id"], "filename": record["filename"], "sha256": record["sha256"], "risk_score": analysis["risk"]["score"], **finding})
    return output.getvalue()
